const { contextBridge, ipcRenderer } = require('electron');

async function invokeRequest(channel, ...args) {
  const result = await ipcRenderer.invoke(channel, ...args);
  if (!result || typeof result.ok !== 'boolean') {
    throw new Error('استجابة غير صالحة من التطبيق.');
  }
  if (!result.ok) {
    throw new Error(result.error?.message || 'تعذر تنفيذ الطلب.');
  }
  return result.data;
}

